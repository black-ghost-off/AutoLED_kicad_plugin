def to_cut_svg(loops):
    """Closed cut-line loops (board mm) as an SVG with real mm units."""
    xs = [x for loop in loops for x, _ in loop]
    ys = [y for loop in loops for _, y in loop]
    x0, y0 = min(xs), min(ys)
    w, h = max(xs) - x0, max(ys) - y0
    paths = []
    for loop in loops:
        d = "M " + " L ".join("%.4f %.4f" % (x - x0, y - y0) for x, y in loop) + " Z"
        paths.append('  <path d="%s"/>' % d)
    return "\n".join([
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<svg xmlns="http://www.w3.org/2000/svg" width="%.4fmm" height="%.4fmm" '
        'viewBox="0 0 %.4f %.4f">' % (w, h, w, h),
        '<g fill="none" stroke="#ff0000" stroke-width="0.1">',
    ] + paths + ["</g>", "</svg>", ""])


def to_cut_dxf(loops):
    """Closed cut-line loops (board mm) as DXF R12 LINE entities, Y up."""
    out = ["0", "SECTION", "2", "HEADER", "9", "$INSUNITS", "70", "4", "0", "ENDSEC",
           "0", "SECTION", "2", "ENTITIES"]
    for loop in loops:
        for (ax, ay), (bx, by) in zip(loop, loop[1:] + loop[:1]):
            out += ["0", "LINE", "8", "CUT",
                    "10", "%.4f" % ax, "20", "%.4f" % -ay, "30", "0",
                    "11", "%.4f" % bx, "21", "%.4f" % -by, "31", "0"]
    out += ["0", "ENDSEC", "0", "EOF", ""]
    return "\n".join(out)
